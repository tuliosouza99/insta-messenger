const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

// Xcode builds with the checked-in resources, without requiring Node.
async function main() {
  const outdir = path.resolve(__dirname, '../ios/InstagramMessenger/Resources');
  const result = await esbuild.build({
    entryPoints: {
      focus: path.resolve(__dirname, '../ios/focus-entry.js'),
      links: path.resolve(__dirname, '../ios/links-entry.js'),
    },
    outdir,
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: 'safari17',
    legalComments: 'none',
    write: false,
    banner: { js: '// Generated by npm run build:ios. Edit ios/ or the shared focus and policy source.' },
  });

  if (process.argv.includes('--check')) {
    for (const { path: file, text } of result.outputFiles) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) {
        throw new Error(`${path.basename(file)} is stale. Run npm run build:ios.`);
      }
    }
    console.log('iPhone browser resources are current.');
    return;
  }

  fs.mkdirSync(outdir, { recursive: true });
  for (const { path: file, text } of result.outputFiles) {
    fs.writeFileSync(file, text);
    console.log(`Generated ${file}`);
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
