const esbuild = require('esbuild');
const path = require('node:path');

// Commit the generated resource so opening the Xcode project never needs Node.
// --check detects stale resources without changing the working tree.
async function main() {
  const fs = require('node:fs');
  const outfile = path.resolve(__dirname, '../ios/InstagramMessenger/Resources/focus.js');
  const result = await esbuild.build({
    entryPoints: [path.resolve(__dirname, '../ios/focus-entry.js')], outfile,
    bundle: true, platform: 'browser', format: 'iife', target: 'safari17',
    legalComments: 'none', write: false,
    banner: { js: '// Generated by node scripts/build-ios.js. Edit ios/focus-entry.js or shared src policy/focus instead.' },
  });
  const output = result.outputFiles[0].text;
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(outfile) || fs.readFileSync(outfile, 'utf8') !== output) {
      throw new Error('iPhone focus resource is stale. Run node scripts/build-ios.js.');
    }
    console.log('iPhone focus resource is current.');
  } else {
    fs.mkdirSync(path.dirname(outfile), { recursive: true });
    fs.writeFileSync(outfile, output);
    console.log(`Generated ${outfile}`);
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
